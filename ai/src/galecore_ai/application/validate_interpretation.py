"""Transport-neutral post-model assurance. Never invokes a model or a transport.

The caller owns fact acquisition and provenance. Acceptance covers only the
returned payload; it does not certify later prose generated by a host.

Near-zero regime validation:
  DISABLED. GaleCore publishes call_gex/put_gex in millions and net_gex in
  billions (see GammaExposureResponse.cs). The previous formula
  ``|net_gex| / (|call_gex| + |put_gex|) * 100`` compared values in
  incompatible scales. Until GaleCore-AI receives normalized facts or
  GaleCore publishes unit metadata, near_zero is always rejected.
  The convention entry ``gex_near_zero_threshold_pct`` is preserved in
  ``config/conventions/trading-defaults.yaml`` for future use but does NOT
  enable near_zero validation.

Quantitative claims:
  The host provides structured ``QuantitativeClaim`` objects (metric, value,
  unit). The validator derives fact_path and expected unit from
  ``METRIC_REGISTRY`` and requires value to equal the authoritative fact
  exactly (``==``) — no scaling, rounding, tolerance or normalization.
  Numbers in observations/implications are forbidden (fail-closed).

Semantic limits (documented, not solved): qualitative prose is not checked
for entailment; EvidenceRef only proves the referenced path resolves.
"""

from __future__ import annotations

import math

from pydantic import BaseModel, Field, ValidationError

from galecore_ai.contracts.gex_analysis import (
    METRIC_REGISTRY,
    GexInterpretation,
    GexRegime,
    QuantitativeClaim,
)
from galecore_ai.contracts.regime_analysis import (
    REGIME_METRIC_REGISTRY,
    RegimeInterpretation,
    RegimeQuantitativeClaim,
    TailPricing,
)
from galecore_ai.harness.guardrails import GuardrailResult, GuardrailRunner, check_all_passed

# Checks that need the parsed interpretation, not raw text. They are run
# here and must not be looked up in the raw-text GuardrailRunner.
_STRUCTURAL_GEX_CHECKS = ("gex_regime_sign", "quantitative_claims_valid", "tail_pricing_level")

# Required for every GexInterpretation / RegimeInterpretation regardless of
# what the protocol lists.
_REQUIRED_GEX_TEXT_CHECKS = (
    "no_invented_numbers",
    "facts_match_source",
    "no_trading_recommendation",
    "no_numbers_in_prose",
)


class InterpretationValidation(BaseModel):
    accepted: bool
    result: dict | None = None
    checks: list[GuardrailResult] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)


def validate_interpretation(
    *,
    interpretation: dict | str,
    facts: dict,
    output_schema: type[BaseModel],
    guardrail_ids: list[str],
    guardrail_runner: GuardrailRunner | None = None,
) -> InterpretationValidation:
    """Reparse and validate the exact payload that will cross the boundary."""
    try:
        value = (
            output_schema.model_validate_json(interpretation)
            if isinstance(interpretation, str)
            else output_schema.model_validate(interpretation)
        )
    except ValidationError as exc:
        return InterpretationValidation(accepted=False, errors=[str(exc)])

    ids = list(dict.fromkeys(guardrail_ids))
    structured = isinstance(value, (GexInterpretation, RegimeInterpretation))
    if structured:
        # Required checks cannot be disabled by an omitted protocol entry,
        # and structural checks always run here on the parsed model.
        ids = [gid for gid in [*ids, *_REQUIRED_GEX_TEXT_CHECKS] if gid not in _STRUCTURAL_GEX_CHECKS]
        ids = list(dict.fromkeys(ids))
    if not ids:
        return InterpretationValidation(accepted=False, errors=["No assurance checks configured"])

    checks = (guardrail_runner or GuardrailRunner()).run_all(
        guardrail_ids=ids, raw_text=value.model_dump_json(), facts=facts,
    )
    if isinstance(value, GexInterpretation):
        checks.append(_check_regime_sign(value.regime, facts))
        checks.extend(
            _validate_single_claim(c, facts, i, METRIC_REGISTRY)
            for i, c in enumerate(value.quantitative_claims)
        )
    elif isinstance(value, RegimeInterpretation):
        checks.append(_check_regime_sign(value.gamma_regime, facts))
        checks.append(_check_tail_pricing(value.tail_pricing, facts))
        checks.extend(
            _validate_single_claim(c, facts, i, REGIME_METRIC_REGISTRY)
            for i, c in enumerate(value.quantitative_claims)
        )

    accepted = check_all_passed(checks)
    return InterpretationValidation(
        accepted=accepted,
        result=value.model_dump(mode="json") if accepted else None,
        checks=checks,
        errors=[f"{c.guardrail_id}: {c.message}" for c in checks if not c.passed],
    )


def _check_regime_sign(
    regime: GexRegime,
    facts: dict,
) -> GuardrailResult:
    """Validate gamma regime classification against facts.

    - positive_gamma: net_gex > 0
    - negative_gamma: net_gex < 0
    - near_zero: ALWAYS REJECTED — call_gex/put_gex and net_gex use
      incompatible scales (millions vs billions). Fail-closed until
      normalized facts are available.
    """
    net = facts.get("net_gex")
    valid = isinstance(net, (int, float)) and not isinstance(net, bool)
    msg = ""

    if not valid:
        msg = "net_gex missing or not numeric"
    elif not math.isfinite(net):
        valid = False
        msg = "net_gex is not finite"
    elif regime.value == "near_zero":
        valid = False
        msg = (
            "near_zero validation unavailable: GaleCore call_gex/put_gex and "
            "net_gex use incompatible scales (millions vs billions); "
            "fail-closed until normalized facts are available"
        )
    elif regime.value == "positive_gamma" and net <= 0:
        valid = False
        msg = f"positive_gamma requires net_gex > 0, got {net}"
    elif regime.value == "negative_gamma" and net >= 0:
        valid = False
        msg = f"negative_gamma requires net_gex < 0, got {net}"

    return GuardrailResult(
        guardrail_id="gex_regime_sign",
        passed=valid,
        message=msg or "Regime sign validated",
    )


def _check_tail_pricing(tail_pricing: TailPricing, facts: dict) -> GuardrailResult:
    """tail_pricing must agree with GaleCore's own level semaphore.

    ``calm`` iff facts.put_skew_level_ok is true; ``elevated`` iff false. The
    flag and its threshold are GaleCore's; a missing or non-boolean flag fails
    closed.
    """
    flag = facts.get("put_skew_level_ok")
    if not isinstance(flag, bool):
        return GuardrailResult(
            guardrail_id="tail_pricing_level", passed=False,
            message="put_skew_level_ok missing or not boolean",
        )
    expected = TailPricing.CALM if flag else TailPricing.ELEVATED
    if tail_pricing != expected:
        return GuardrailResult(
            guardrail_id="tail_pricing_level", passed=False,
            message=(
                f"tail_pricing '{tail_pricing.value}' contradicts put_skew_level_ok={flag} "
                f"(expected '{expected.value}')"
            ),
        )
    return GuardrailResult(
        guardrail_id="tail_pricing_level", passed=True,
        message="tail_pricing agrees with GaleCore's put_skew_level_ok",
    )


def _validate_single_claim(
    claim: QuantitativeClaim | RegimeQuantitativeClaim,
    facts: dict,
    index: int,
    registry: dict,
) -> GuardrailResult:
    """Validate a single quantitative claim against the authoritative facts.

      1. Look up the metric in the skill's registry -> expected fact_path and unit
      2. Resolve fact_path in facts -> must be a finite scalar
      3. Require claim.value to equal the fact value
      4. Verify claim.unit matches expected unit
    """
    gid = "quantitative_claims_valid"

    spec = registry.get(claim.metric)
    if spec is None:
        # Should not happen with enum validation, but fail-closed
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: metric '{claim.metric}' not in registry",
        )

    # Unit must match
    if claim.unit != spec.unit:
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=(
                f"Claim[{index}]: metric '{claim.metric.value}' requires "
                f"unit '{spec.unit.value}', got '{claim.unit.value}'"
            ),
        )

    # Claim value must be finite
    if not math.isfinite(claim.value):
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: value is not finite ({claim.value})",
        )

    # Resolve fact_path
    fact_key = spec.fact_path.removeprefix("facts.")
    fact_value = facts.get(fact_key)

    if fact_value is None:
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: fact '{spec.fact_path}' is absent or null",
        )

    if isinstance(fact_value, (dict, list)):
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: fact '{spec.fact_path}' is not a scalar",
        )

    if not isinstance(fact_value, (int, float)) or isinstance(fact_value, bool):
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: fact '{spec.fact_path}' is not numeric",
        )

    if not math.isfinite(fact_value):
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=f"Claim[{index}]: fact '{spec.fact_path}' is not finite",
        )

    # Exact equality. Facts and claims both arrive through JSON, so the
    # float values are comparable bit-for-bit; any rounding, rescaling or
    # truncation by the host is rejected.
    if claim.value != float(fact_value):
        return GuardrailResult(
            guardrail_id=gid, passed=False,
            message=(
                f"Claim[{index}]: metric '{claim.metric.value}' value "
                f"{claim.value} does not match fact {float(fact_value)}"
            ),
        )

    return GuardrailResult(
        guardrail_id=gid, passed=True,
        message=f"Claim[{index}]: metric '{claim.metric.value}' validated",
    )
