"""GEX Interpretation skill — the first skill for Phase 3.

Teaches the agent how to interpret gamma exposure data.
facts = GexFacts from GaleCore's compute.gamma_exposure capability.
interpretation = GexInterpretation generated by the model.
"""

from __future__ import annotations

from galecore_ai.harness.definitions import SkillDefinition, SkillExample


def build_gex_interpretation_skill() -> SkillDefinition:
    """Build the GEX interpretation skill definition."""
    return SkillDefinition(
        skill_id="gex_interpretation",
        version="1.0.0",
        display_name="GEX Interpretation",
        description="Interprets gamma exposure data to assess dealer positioning and expected market behavior.",
        required_capabilities=["compute.gamma_exposure"],
        output_contract="galecore_ai.contracts.gex_analysis.GexInterpretation",
        system_prompt=(
            "You are a gamma exposure analyst. Your role is to interpret GEX data "
            "provided as deterministic facts from GaleCore's compute engine.\n\n"
            "Rules:\n"
            "1. NEVER invent, recalculate, or estimate quantitative values.\n"
            "2. Only reference numbers that appear in the provided facts.\n"
            "3. Classify the regime as: positive_gamma, negative_gamma, or near_zero.\n"
            "4. Provide actionable observations about dealer positioning.\n"
            "5. State implications for expected price behavior.\n"
            "6. Include caveats about data limitations."
        ),
        instructions=(
            "Given the GEX facts below, produce a GexInterpretation with:\n"
            "- regime: one of 'positive_gamma', 'negative_gamma', 'near_zero'\n"
            "- observations: what the data shows about dealer positioning\n"
            "- implications: what this means for expected price behavior\n"
            "- caveats: limitations and conditions that could change the analysis\n\n"
            "Regime classification rules:\n"
            "- net_gex > 0 → positive_gamma (dealers are long gamma, expect mean reversion)\n"
            "- net_gex < 0 → negative_gamma (dealers are short gamma, expect amplified moves)\n"
            "- |net_gex| < threshold → near_zero (neutral zone, regime could shift)\n\n"
            "The threshold for near_zero is context-dependent. Use the relationship between "
            "net_gex and the absolute values of call_gex and put_gex to judge significance."
        ),
        examples=[
            SkillExample(
                input_summary="SPY with positive net GEX, spot above zero-gamma level",
                expected_output={
                    "regime": "positive_gamma",
                    "observations": [
                        "Net GEX is positive — dealers are long gamma",
                        "Spot is above the zero-gamma level",
                    ],
                    "implications": [
                        "Dealers will sell into rallies and buy dips, dampening volatility",
                        "Expect mean-reverting price action within the call wall / put wall range",
                    ],
                    "caveats": [
                        "GEX is a snapshot based on current open interest and may shift with new flow",
                        "Intraday dealer hedging dynamics depend on realized volume",
                    ],
                },
            ),
        ],
    )
